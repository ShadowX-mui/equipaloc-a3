-- =====================================================================
-- EquipaLoc - DDL Oracle XE 21
-- Roda do zero. Diferencas em relacao ao PostgreSQL:
--   VARCHAR2/NUMBER, DEFAULT SYSDATE/SYSTIMESTAMP e ausencia de RESTRICT:
--   o Oracle nao aceita ON DELETE RESTRICT; omitir a clausula ja BLOQUEIA
--   a exclusao do pai (ORA-02292). Por isso o "RESTRICT" aparece so em comentario.
-- =====================================================================

CREATE TABLE perfil_cliente (
    perfil_id          NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    nome               VARCHAR2(20) NOT NULL,
    max_itens_abertos  NUMBER(3)    NOT NULL,
    CONSTRAINT pk_perfil_cliente PRIMARY KEY (perfil_id),
    CONSTRAINT uk_perfil_nome    UNIQUE (nome),
    CONSTRAINT ck_perfil_max     CHECK (max_itens_abertos BETWEEN 1 AND 20)
);

CREATE TABLE cliente (
    cliente_id     NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    perfil_id      NUMBER(10)    NOT NULL,
    nome           VARCHAR2(60)  NOT NULL,
    email          VARCHAR2(80)  NOT NULL,
    data_cadastro  DATE          DEFAULT TRUNC(SYSDATE) NOT NULL,
    CONSTRAINT pk_cliente        PRIMARY KEY (cliente_id),
    CONSTRAINT uk_cliente_email  UNIQUE (email),
    CONSTRAINT fk_cliente_perfil FOREIGN KEY (perfil_id)
        REFERENCES perfil_cliente (perfil_id)   -- RESTRICT (padrao do Oracle)
);

CREATE TABLE categoria (
    categoria_id  NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    nome          VARCHAR2(40) NOT NULL,
    CONSTRAINT pk_categoria      PRIMARY KEY (categoria_id),
    CONSTRAINT uk_categoria_nome UNIQUE (nome)
);

CREATE TABLE equipamento (
    equipamento_id   NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    categoria_id     NUMBER(10)    NOT NULL,
    codigo           VARCHAR2(20)  NOT NULL,
    descricao        VARCHAR2(80)  NOT NULL,
    valor_diaria     NUMBER(10,2)  NOT NULL,
    valor_reposicao  NUMBER(10,2)  NOT NULL,
    status           VARCHAR2(12)  DEFAULT 'DISPONIVEL' NOT NULL,
    CONSTRAINT pk_equipamento     PRIMARY KEY (equipamento_id),
    CONSTRAINT uk_equip_codigo    UNIQUE (codigo),
    CONSTRAINT ck_equip_diaria    CHECK (valor_diaria > 0),
    CONSTRAINT ck_equip_reposicao CHECK (valor_reposicao > 0),
    CONSTRAINT ck_equip_status    CHECK (status IN ('DISPONIVEL','ALUGADO','MANUTENCAO')),
    CONSTRAINT fk_equip_categoria FOREIGN KEY (categoria_id)
        REFERENCES categoria (categoria_id)     -- RESTRICT (padrao do Oracle)
);

CREATE TABLE locacao (
    locacao_id      NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    cliente_id      NUMBER(10)   NOT NULL,
    data_saida      DATE         NOT NULL,
    data_prevista   DATE         NOT NULL,
    data_devolucao  DATE,
    status          VARCHAR2(10) DEFAULT 'ABERTA' NOT NULL,
    CONSTRAINT pk_locacao         PRIMARY KEY (locacao_id),
    CONSTRAINT fk_locacao_cliente FOREIGN KEY (cliente_id)
        REFERENCES cliente (cliente_id),        -- RESTRICT (padrao do Oracle)
    CONSTRAINT ck_locacao_status  CHECK (status IN ('ABERTA','DEVOLVIDA')),
    CONSTRAINT ck_locacao_prazo   CHECK (data_prevista - data_saida BETWEEN 1 AND 15),
    CONSTRAINT ck_locacao_dev_data CHECK (data_devolucao IS NULL OR data_devolucao >= data_saida),
    CONSTRAINT ck_locacao_status_dev CHECK (
        (status = 'ABERTA'    AND data_devolucao IS NULL) OR
        (status = 'DEVOLVIDA' AND data_devolucao IS NOT NULL))
);

CREATE TABLE item_locacao (
    item_id               NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    locacao_id            NUMBER(10)   NOT NULL,
    equipamento_id        NUMBER(10)   NOT NULL,
    valor_diaria_cobrada  NUMBER(10,2) NOT NULL,
    avaria                CHAR(1)      DEFAULT 'N' NOT NULL,
    CONSTRAINT pk_item_locacao     PRIMARY KEY (item_id),
    CONSTRAINT uk_item_loc_equip   UNIQUE (locacao_id, equipamento_id),
    CONSTRAINT fk_item_locacao     FOREIGN KEY (locacao_id)
        REFERENCES locacao (locacao_id) ON DELETE CASCADE,
    CONSTRAINT fk_item_equipamento FOREIGN KEY (equipamento_id)
        REFERENCES equipamento (equipamento_id), -- RESTRICT (padrao do Oracle)
    CONSTRAINT ck_item_diaria      CHECK (valor_diaria_cobrada > 0),
    CONSTRAINT ck_item_avaria      CHECK (avaria IN ('S','N'))
);

CREATE TABLE multa (
    multa_id      NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    locacao_id    NUMBER(10)   NOT NULL,
    tipo          VARCHAR2(10) NOT NULL,
    valor         NUMBER(10,2) NOT NULL,
    status        VARCHAR2(10) DEFAULT 'ABERTA' NOT NULL,
    data_geracao  DATE         NOT NULL,
    CONSTRAINT pk_multa          PRIMARY KEY (multa_id),
    CONSTRAINT uk_multa_loc_tipo UNIQUE (locacao_id, tipo),
    CONSTRAINT fk_multa_locacao  FOREIGN KEY (locacao_id)
        REFERENCES locacao (locacao_id),         -- RESTRICT (padrao do Oracle)
    CONSTRAINT ck_multa_tipo     CHECK (tipo IN ('ATRASO','AVARIA')),
    CONSTRAINT ck_multa_valor    CHECK (valor >= 0),
    CONSTRAINT ck_multa_status   CHECK (status IN ('ABERTA','PAGA'))
);

-- Auditoria: de proposito SEM FK para a historia sobreviver a exclusao da locacao
CREATE TABLE auditoria_locacao (
    auditoria_id     NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    locacao_id       NUMBER(10)   NOT NULL,
    operacao         VARCHAR2(10) NOT NULL,
    status_anterior  VARCHAR2(10),
    status_novo      VARCHAR2(10),
    usuario          VARCHAR2(40) NOT NULL,
    data_evento      TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_auditoria PRIMARY KEY (auditoria_id)
);
